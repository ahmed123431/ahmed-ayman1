// CONTEXT
// ========================================

const LanguageContext = createContext<LanguageContextType | undefined>(undefined);

// ========================================
// PROVIDER
// ========================================

export function LanguageProvider({ children }: { children: ReactNode }) {
    const [language, setLanguageState] = useState<Language>(() => {
        // Try to get from localStorage
        const saved = localStorage.getItem('rcm-language');
        if (saved && (saved === 'en' || saved === 'ar')) {
            return saved as Language;
        }
        // Default to English
        return 'en';
    });

    const currentLang = languages.find(l => l.code === language) || languages[0];
    const direction = currentLang.direction;

    // Update document direction and save preference
    useEffect(() => {
        document.documentElement.dir = direction;
        document.documentElement.lang = language;
        localStorage.setItem('rcm-language', language);

        // Add RTL-specific styles
        if (direction === 'rtl') {
            document.body.style.fontFamily = "'Cairo', 'Inter', sans-serif";
        } else {
            document.body.style.fontFamily = "'Inter', sans-serif";
        }
    }, [language, direction]);

    const setLanguage = (lang: Language) => {
        setLanguageState(lang);
    };

    // Translation function
    const t = (key: string): string => {
        return translations[language][key] || translations['en'][key] || key;
    };

    return (
        <LanguageContext.Provider value={{ language, setLanguage, t, direction, languages }}>
            {children}
        </LanguageContext.Provider>
    );
}

// ========================================
// HOOK
// ========================================

export function useLanguage() {
    const context = useContext(LanguageContext);
    if (context === undefined) {
        throw new Error('useLanguage must be used within a LanguageProvider');
    }
    return context;
}
